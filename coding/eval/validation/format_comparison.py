"""Generate outputs/revision/comparison_macro_f1.md from the recompute outputs.

Consumes:
  * outputs/revision/metrics_recomputed.parquet (recompute_all_macro.py)
  * outputs/revision/bootstrap_recomputed.parquet (recompute_paired_bootstraps.py)

Sections (per playbook §Phase 4 #14-#16):
  1. Side-by-side macro-F1 table for every (system, test, condition)
  2. Ranking-preservation check per (test, condition)
  3. Headline-delta robustness check vs the abstract claims
  4. OOD scorable-set sizes (flag <200)
  5. STOP-gate yes/no answers

Run with: ``uv run python revision/format_comparison.py``
"""
from __future__ import annotations

import sys

import polars as pl

from coding.eval.harness import OUT_DIR, REPO_ROOT, SPEC

DATASETS = (SPEC.name,)


SYSTEM_ORDER = [
    "sft_only_tau_macro",
    "sft_only_tau_micro",
    "sft_band_verify",
    "gap_fill_intermediate",
    "full_pipeline",
]
SYSTEM_DISPLAY = {
    "sft_only_tau_macro": "SFT @ τ*_macro",
    "sft_only_tau_micro": "SFT @ τ*_micro (= sft_high)",
    "sft_band_verify": "+band_verify",
    "gap_fill_intermediate": "+gap_fill (raw)",
    "full_pipeline": "Hybrid (+verify_gap_fill)",
}
SCOPE_ORDER = ["in_dist", "ood", "full"]


def _fmt(x: float, *, places: int = 4) -> str:
    if x != x:  # NaN
        return "N/A"
    return f"{x:.{places}f}"


def _fmt_delta(a: float, b: float, *, places: int = 4) -> str:
    if a != a or b != b:
        return "N/A"
    d = a - b
    sign = "+" if d >= 0 else ""
    return f"{sign}{d:.{places}f}"


def main() -> int:
    metrics = pl.read_parquet(OUT_DIR / "metrics_recomputed.parquet")
    boots = pl.read_parquet(OUT_DIR / "bootstrap_recomputed.parquet")

    out = []
    out.append("# Macro-F1 recompute: full vs scorable denominator\n")
    out.append("Generated by `revision/format_comparison.py`. "
               "Source data: `metrics_recomputed.parquet`, `bootstrap_recomputed.parquet`.\n")
    out.append("Reproducibility: every `micro_f1` and `macro_f1_full` in this report "
               "matches the corresponding value in `outputs/revision/results/.../*.json` to 4 decimal places "
               "(verified by `recompute_all_macro.py`).\n")

    # --- Section 1: side-by-side table -------------------------------------
    out.append("\n## 1. Side-by-side macro-F1 (full vs scorable)\n")
    out.append("| system | test | condition | micro | macro_full | macro_scorable | Δ (scor − full) | N_scorable | N_in_scope |")
    out.append("|---|---|---|---:|---:|---:|---:|---:|---:|")
    for ts in DATASETS:
        sub = metrics.filter(pl.col("test_set") == ts)
        for sys_name in SYSTEM_ORDER:
            for scope in SCOPE_ORDER:
                rec = sub.filter((pl.col("system") == sys_name) & (pl.col("condition") == scope))
                if rec.height == 0:
                    continue
                r = rec.row(0, named=True)
                out.append(
                    f"| {SYSTEM_DISPLAY[sys_name]} | {ts} | {scope} "
                    f"| {_fmt(r['micro_f1'])} "
                    f"| {_fmt(r['macro_f1_full'])} "
                    f"| {_fmt(r['macro_f1_scorable'])} "
                    f"| {_fmt_delta(r['macro_f1_scorable'], r['macro_f1_full'])} "
                    f"| {r['n_scorable']} | {r['n_in_scope']} |"
                )

    # --- Section 2: ranking preservation -----------------------------------
    out.append("\n## 2. Ranking-preservation check\n")
    out.append("For each (test, condition), system ordering under `full` vs `scorable`. "
               "A flip means switching the denominator would reorder Table 1 rows.\n")
    flips: list[str] = []
    for ts in DATASETS:
        for scope in SCOPE_ORDER:
            sub = metrics.filter(
                (pl.col("test_set") == ts) & (pl.col("condition") == scope)
            )
            # Skip if all NaN (e.g. SFT-only on OOD reports 0 by construction —
            # treat as ties under both modes, no flip possible).
            order_full = sub.sort("macro_f1_full", descending=True)["system"].to_list()
            order_scor = sub.sort("macro_f1_scorable", descending=True, nulls_last=True)["system"].to_list()
            if order_full != order_scor:
                flips.append(f"- **{ts} / {scope}**: full ranks {order_full}; scorable ranks {order_scor}")
    if flips:
        out.append("\n".join(flips))
    else:
        out.append("No ranking flips detected. System ordering on macro-F1 is preserved under the scorable denominator.")

    # --- Section 3: headline-delta robustness ------------------------------
    out.append("\n\n## 3. Headline-delta robustness\n")
    out.append(
        "Abstract & intro claim: Hybrid lifts Full macro-F1 by **+0.023** on MIMIC-III "
        "(CI [+0.022, +0.026]) and **+0.006** on MIMIC-IV.\n"
    )
    head = boots.filter(pl.col("comparison") == "full_pipeline_vs_sft_only_tau_macro")
    out.append("| comparison | test | condition | denom | Δmacro | CI (normal) | p (two-sided) |")
    out.append("|---|---|---|---|---:|---|---:|")
    for ts in DATASETS:
        for scope in ("full", "in_dist"):
            for denom in ("full", "scorable"):
                rec = head.filter(
                    (pl.col("test_set") == ts)
                    & (pl.col("condition") == scope)
                    & (pl.col("macro_denominator") == denom)
                )
                if rec.height == 0:
                    continue
                r = rec.row(0, named=True)
                out.append(
                    f"| full_pipeline vs sft_only_tau_macro | {ts} | {scope} | {denom} "
                    f"| {r['delta_macro']:+.4f} "
                    f"| [{r['delta_macro_ci_lo']:+.4f}, {r['delta_macro_ci_hi']:+.4f}] "
                    f"| {r['p_macro_two_sided']:.4f} |"
                )

    # Sign + size check on the headline cells
    abstract_full = head.filter(
        (pl.col("condition") == "full") & (pl.col("macro_denominator") == "full")
    )
    abstract_scor = head.filter(
        (pl.col("condition") == "full") & (pl.col("macro_denominator") == "scorable")
    )
    expected = {"mimic_iii_clean": 0.023, "mimic_iv": 0.006}
    out.append("\n**Sign/size check:**\n")
    for ts, claimed in expected.items():
        if ts not in DATASETS:
            continue
        f_rec = abstract_full.filter(pl.col("test_set") == ts)
        s_rec = abstract_scor.filter(pl.col("test_set") == ts)
        if f_rec.height == 0 or s_rec.height == 0:
            continue
        f = f_rec.row(0, named=True)["delta_macro"]
        s = s_rec.row(0, named=True)["delta_macro"]
        out.append(
            f"- {ts}: paper claim **{claimed:+.3f}** | recomputed `full` = **{f:+.4f}** "
            f"(diff vs claim: {f - claimed:+.4f}) | `scorable` = **{s:+.4f}** "
            f"(diff vs claim: {s - claimed:+.4f})."
        )

    # --- Section 4: OOD scorable set sizes ---------------------------------
    out.append("\n\n## 4. OOD scorable-set sizes\n")
    out.append("Bootstrap CIs widen sharply when N_scorable < 200. We report the "
               "scorable-set size on the OOD vocab per system.\n")
    out.append("| test | system | N_scorable_OOD | N_in_scope_OOD | flag |")
    out.append("|---|---|---:|---:|---|")
    ood = metrics.filter(pl.col("condition") == "ood").sort(["test_set", "system"])
    for r in ood.iter_rows(named=True):
        flag = "**<200**" if r["n_scorable"] < 200 else "ok"
        out.append(
            f"| {r['test_set']} | {SYSTEM_DISPLAY.get(r['system'], r['system'])} "
            f"| {r['n_scorable']} | {r['n_in_scope']} | {flag} |"
        )

    # --- Section 5: STOP-gate answers --------------------------------------
    out.append("\n\n## 5. STOP-gate (playbook §Phase 4 #16)\n")
    # Headline delta sign / magnitude check
    triggers: list[str] = []
    for ts, claimed in expected.items():
        if ts not in DATASETS:
            continue
        f_rec = abstract_full.filter(pl.col("test_set") == ts)
        s_rec = abstract_scor.filter(pl.col("test_set") == ts)
        if f_rec.height == 0 or s_rec.height == 0:
            continue
        f_row = f_rec.row(0, named=True)
        s_row = s_rec.row(0, named=True)
        for tag, val in (("full", f_row["delta_macro"]), ("scorable", s_row["delta_macro"])):
            # Sign flip
            if val * claimed < 0:
                triggers.append(
                    f"- SIGN FLIP: {ts} headline under {tag} = {val:+.4f}, claimed {claimed:+.3f}"
                )
            # Magnitude shift > 0.01
            if abs(val - claimed) > 0.01:
                triggers.append(
                    f"- MAGNITUDE SHIFT > 0.01: {ts} under {tag} = {val:+.4f} vs claimed {claimed:+.3f} "
                    f"(|Δ|={abs(val - claimed):.4f})"
                )

    # Hybrid vs SFT-macro InDist parity check
    indist = boots.filter(
        (pl.col("comparison") == "full_pipeline_vs_sft_only_tau_macro")
        & (pl.col("condition") == "in_dist")
    )
    for r in indist.iter_rows(named=True):
        if abs(r["delta_macro"]) > 0.005:
            triggers.append(
                f"- HYBRID vs SFT-MACRO InDist gap > 0.005: {r['test_set']} "
                f"under {r['macro_denominator']} = {r['delta_macro']:+.4f}"
            )

    # Micro-F1 reproducibility (driver's per-cell assertion)
    n_bad_micro = metrics.filter(~pl.col("reproducibility_status").str.starts_with("OK")).height
    if n_bad_micro:
        triggers.append(f"- MICRO-F1 REPRODUCIBILITY FAILURE: {n_bad_micro} cells deviate from cached JSONs")

    out.append("\n**Trigger 1 — any headline delta sign-flip or |Δ| > 0.01 vs claim:**")
    sign_or_mag = [t for t in triggers if t.startswith("- SIGN FLIP") or t.startswith("- MAGNITUDE SHIFT")]
    if sign_or_mag:
        out.append("\n**YES — trigger fired:**\n" + "\n".join(sign_or_mag))
    else:
        out.append("\nNo. Both headline deltas keep the same sign and shift < 0.01 vs the published claims under both denominators.")
    out.append("\n**Trigger 2 — Hybrid vs SFT-macro InDist parity gap > 0.005:**")
    parity = [t for t in triggers if t.startswith("- HYBRID vs SFT-MACRO")]
    if parity:
        out.append("\n**YES — trigger fired:**\n" + "\n".join(parity))
    else:
        out.append("\nNo. InDist macro parity holds (|Δ| ≤ 0.005) on both datasets and both denominators.")
    out.append("\n**Trigger 3 — Micro-F1 differs from existing JSON:**")
    if n_bad_micro:
        out.append("\n**YES — trigger fired** (see status column of metrics_recomputed.parquet).")
    else:
        out.append("\nNo. Every cell's micro_f1 matches the cached JSON to 4dp.")

    out.append("\n## 6. Notes\n")
    out.append("- `sft_only_*` rows on OOD report 0 by construction (SFT vocabulary is disjoint from the OOD test vocabulary). "
               "We surface them as 0.0 rather than N/A to preserve the existing table layout; the playbook recommends "
               "footnoting them as N/A in the paper itself.")
    out.append("- `gap_fill_intermediate` is the intermediate stage (sft_micro ∪ band_verify ∪ raw_gap_candidates) "
               "used in `tab:stages`; the LLM-verified version is `full_pipeline`.")
    out.append("- Stage deltas for `tab:stages` (+band_verify vs sft_high, +verify_gap_fill vs +band_verify) "
               "are in `bootstrap_recomputed.parquet` — see Section 3.")

    text = "\n".join(out) + "\n"
    out_path = OUT_DIR / "comparison_macro_f1.md"
    out_path.write_text(text)
    print(f"Wrote {out_path.relative_to(REPO_ROOT)} ({len(text)} bytes)")
    if triggers:
        print(f"\n*** {len(triggers)} STOP-gate triggers fired — review the report ***")
    return 0


if __name__ == "__main__":
    sys.exit(main())
